const router = require('express').Router();
const controller = require('../controllers/azureController');
const { authenticate } = require('../middleware/authMiddleware');
router.use(authenticate);
router.get('/resources', controller.resources);
router.get('/vms', controller.vms);
router.get('/storage', controller.storage);
router.get('/databases', controller.databases);
router.get('/vms/:resourceId', controller.vmDetail);
router.get('/metrics/vm/:resourceId', controller.metrics);
router.get('/metrics/storage/:resourceId', controller.storageMetrics);
router.get('/metrics/database/:resourceId', controller.databaseMetrics);
router.get('/pricing/vms', controller.pricing);
router.get('/pricing/storage', controller.storagePricing);
router.get('/pricing/databases', controller.databasePricing);
router.get('/dashboard', controller.dashboard);
module.exports = router;
