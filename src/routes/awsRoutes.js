const router = require("express").Router();
const controller = require("../controllers/awsController");
const { authenticate } = require("../middleware/authMiddleware");
router.use(authenticate);
router.get("/resources", controller.resources);
router.get("/ec2", controller.ec2);
router.get("/s3", controller.s3);
router.get("/rds", controller.rds);
router.get("/ec2/:instanceId", controller.ec2Detail);
router.get("/s3/:bucketName", controller.s3Detail);
router.get("/rds/:dbIdentifier", controller.rdsDetail);
router.get("/metrics/ec2/:instanceId", controller.metrics);
router.get("/metrics/s3/:bucketName", controller.s3Metrics);
router.get("/metrics/rds/:dbIdentifier", controller.rdsMetrics);
router.get("/pricing/ec2", controller.pricing);
router.get("/pricing/s3", controller.s3Pricing);
router.get("/pricing/rds", controller.rdsPricing);
router.get("/dashboard", controller.dashboard);
module.exports = router;
