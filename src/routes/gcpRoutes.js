const router = require("express").Router();
const controller = require("../controllers/gcpController");
const { authenticate } = require("../middleware/authMiddleware");
router.use(authenticate);
router.get("/resources", controller.resources);
router.get("/vms", controller.vms);
router.get("/storage", controller.storage);
router.get("/databases", controller.databases);
router.get("/vms/:instanceId", controller.vmDetail);
router.get("/storage/:bucketName", controller.storageDetail);
router.get("/databases/:instanceName", controller.databaseDetail);
router.get("/metrics/vm/:instanceId", controller.vmMetrics);
router.get("/metrics/storage/:bucketName", controller.storageMetrics);
router.get("/metrics/database/:instanceName", controller.databaseMetrics);
router.get("/pricing/vms", controller.vmPricing);
router.get("/pricing/storage", controller.storagePricing);
router.get("/pricing/databases", controller.databasePricing);
router.get("/dashboard", controller.dashboard);
module.exports = router;
